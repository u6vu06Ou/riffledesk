export const LANG = (() => {
  try { const v = localStorage.getItem('floderLang'); if (v && DICT[v]) return v; } catch (_) {}
  return /^zh/i.test(navigator.language || '') ? 'zh' : 'en';
})();

export function t(key, vars) {
  let s = (DICT[LANG] && DICT[LANG][key]) ?? DICT.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

export function setLang(lang) {
  if (!DICT[lang] || lang === LANG) return;
  try { localStorage.setItem('floderLang', lang); } catch (_) {}
  location.reload();
}

// 靜態 HTML：data-i18n＝文字、data-i18n-title＝提示、data-i18n-ph＝輸入框提示字
export function applyStatic(root = document) {
  document.documentElement.lang = LANG === 'zh' ? 'zh-Hant' : 'en';
  document.title = t('brand');
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-label]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nLabel)); });
  root.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
}
